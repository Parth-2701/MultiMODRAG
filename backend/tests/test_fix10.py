"""
Unit tests for FIX-10: Structured captions with dedicated OCR field.
Verifies Pydantic FrameCaption model, JSON parsing, OCR assembly, and fallback handling.
"""
import pytest
import json
from backend.schema import FrameCaption, parse_and_assemble_caption, GEMINI_PROMPT
from backend.rag.hybrid_retrieval import tokenize
from rank_bm25 import BM25Okapi


def test_frame_caption_pydantic_model():
    c = FrameCaption(
        scene="Auditorium lecture hall",
        subjects=["Professor", "Whiteboard"],
        actions="Speaking to audience",
        on_screen_text="Optimization: Learning Rate = 0.001",
        shot="wide",
    )
    assert c.scene == "Auditorium lecture hall"
    assert "Professor" in c.subjects
    assert c.on_screen_text == "Optimization: Learning Rate = 0.001"
    assert c.shot == "wide"


def test_parse_and_assemble_caption_with_ocr():
    data = {
        "scene": "A computer science lecture",
        "subjects": ["Instructor"],
        "actions": "Writing code on slide",
        "on_screen_text": "def gradient_descent(lr=0.001):",
        "shot": "screen recording",
    }
    raw = json.dumps(data)
    assembled = parse_and_assemble_caption(raw)

    assert "A computer science lecture" in assembled
    assert "Instructor" in assembled
    assert "Visible text: def gradient_descent(lr=0.001):" in assembled


def test_parse_and_assemble_caption_without_ocr():
    data = {
        "scene": "A peaceful meadow",
        "subjects": ["Rabbit", "Butterfly"],
        "actions": "Rabbit sits motionless in grass",
        "on_screen_text": "",
        "shot": "medium shot",
    }
    raw = json.dumps(data)
    assembled = parse_and_assemble_caption(raw)

    assert "A peaceful meadow" in assembled
    assert "Rabbit Butterfly" in assembled
    assert "Visible text:" not in assembled


def test_parse_and_assemble_fenced_markdown_json():
    fenced = """```json
{
    "scene": "Corporate boardroom",
    "subjects": ["CEO"],
    "actions": "Reviewing quarterly earnings",
    "on_screen_text": "Q3 Revenue: $4.5B",
    "shot": "close-up"
}
```"""
    assembled = parse_and_assemble_caption(fenced)
    assert "Corporate boardroom" in assembled
    assert "Visible text: Q3 Revenue: $4.5B" in assembled


def test_parse_and_assemble_fallback_to_raw():
    plain = "This is a plain fallback caption generated by Florence-2 or raw model output."
    assert parse_and_assemble_caption(plain) == plain

    assert parse_and_assemble_caption("") == ""
    assert parse_and_assemble_caption(None) == ""


def test_gemini_prompt_honest_guidelines():
    assert "You see ONE frame from a video" in GEMINI_PROMPT
    assert "Transcribe all readable on-screen text VERBATIM" in GEMINI_PROMPT
    assert "Do not infer identities, intentions" in GEMINI_PROMPT


def test_bm25_retrieval_on_slide_title():
    # Verify that a caption assembled with OCR enables exact BM25 keyword matching
    caption1 = parse_and_assemble_caption(json.dumps({
        "scene": "Lecture slide",
        "subjects": ["diagram"],
        "actions": "displaying flowchart",
        "on_screen_text": "Attention Is All You Need",
        "shot": "slide"
    }))
    caption2 = parse_and_assemble_caption(json.dumps({
        "scene": "Campus outdoors",
        "subjects": ["students walking"],
        "actions": "conversing",
        "on_screen_text": "",
        "shot": "wide"
    }))
    caption3 = parse_and_assemble_caption(json.dumps({
        "scene": "Library reading room",
        "subjects": ["books on table"],
        "actions": "studying quietly",
        "on_screen_text": "",
        "shot": "medium"
    }))

    docs = [caption1, caption2, caption3]
    tokenized_docs = [tokenize(d) for d in docs]
    bm25 = BM25Okapi(tokenized_docs)

    query = 'What slide discusses "Attention Is All You Need"?'
    q_tokens = tokenize(query)
    scores = bm25.get_scores(q_tokens)

    # Caption 1 containing the exact OCR text must strongly outscore Caption 2 and 3
    assert scores[0] > scores[1]
    assert scores[0] > scores[2]
    assert scores[0] > 0.0
